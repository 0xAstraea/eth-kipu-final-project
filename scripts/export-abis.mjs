// Exports the ABIs the frontend needs from the compiled Hardhat artifacts.
// Pure Node.js on purpose: it is outside tsconfig's include and the test suite,
// so it can never affect compilation or `hardhat test`.
//
// Usage (from the repo root): node scripts/export-abis.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactsDir = join(here, "..", "artifacts");
const outDir = join(here, "..", "frontend", "lib", "abis");

const targets = [
  { artifact: "contracts/TeamRegistry.sol/TeamRegistry.json", name: "teamRegistryAbi" },
  { artifact: "contracts/TeamCredential.sol/TeamCredential.json", name: "teamCredentialAbi" },
  { artifact: "@semaphore-protocol/contracts/Semaphore.sol/Semaphore.json", name: "semaphoreAbi" }
];

mkdirSync(outDir, { recursive: true });

const header = "// AUTO-GENERATED by scripts/export-abis.mjs. Do not edit by hand.\n\n";

for (const { artifact, name } of targets) {
  const path = join(artifactsDir, artifact);
  const { abi } = JSON.parse(readFileSync(path, "utf8"));
  const body = `${header}export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  const fileName = `${name.replace(/Abi$/, "")}.ts`;
  writeFileSync(join(outDir, fileName), body);
  console.log(`wrote frontend/lib/abis/${fileName} (${abi.length} entries)`);
}
