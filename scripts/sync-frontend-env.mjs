// Writes frontend/.env.local from a deployment file so the addresses never have to be
// copied by hand. Pure Node.js: outside tsconfig and the test suite.
//
// Usage (from the repo root): node scripts/sync-frontend-env.mjs [network]
// Default network: localhost
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const network = process.argv[2] ?? "localhost";
const statePath = join(here, "..", "deployments", `${network}.json`);
const outPath = join(here, "..", "frontend", ".env.local");

const state = JSON.parse(readFileSync(statePath, "utf8"));
const rpcUrl =
  network === "localhost" || network === "hardhat"
    ? "http://127.0.0.1:8545"
    : (process.env.SEPOLIA_RPC_URL ?? "");

const lines = [
  `# Generated by scripts/sync-frontend-env.mjs from deployments/${network}.json`,
  `NEXT_PUBLIC_CHAIN_ID=${state.chainId}`,
  `NEXT_PUBLIC_RPC_URL=${rpcUrl}`,
  `NEXT_PUBLIC_REGISTRY_ADDRESS=${state.teamRegistry}`,
  `NEXT_PUBLIC_CREDENTIAL_ADDRESS=${state.teamCredential}`,
  `NEXT_PUBLIC_SEMAPHORE_ADDRESS=${state.semaphore}`,
  "NEXT_PUBLIC_FROM_BLOCK=0",
  ""
];

writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote frontend/.env.local for '${network}' (owner ${state.owner ?? state.deployer})`);
